  /* ============================================================== SOLVER == */
  /* The whole engine rests on this: encode every possible combination of
     levels as an integer, walk the graph, and never serve a target that the
     search has not actually reached. */

  function Space(caps, sealed) {
    this.caps = caps;
    this.sealed = sealed;
    this.n = caps.length;
    this.mult = [];
    var total = 1;
    for (var i = 0; i < this.n; i++) { this.mult.push(total); total *= caps[i] + 1; }
    this.total = total;
  }

  Space.prototype.encode = function (a) {
    var v = 0;
    for (var i = 0; i < this.n; i++) v += a[i] * this.mult[i];
    return v;
  };

  Space.prototype.decode = function (code) {
    var a = [];
    for (var i = 0; i < this.n; i++) a.push(Math.floor(code / this.mult[i]) % (this.caps[i] + 1));
    return a;
  };

  /** Every legal move out of `code`, as [{ move, to }]. */
  Space.prototype.edges = function (code) {
    var a = this.decode(code), out = [], i, j;
    if (!this.sealed) {
      for (i = 0; i < this.n; i++) {
        if (a[i] < this.caps[i]) out.push({ move: { kind: 'fill', i: i }, to: code + (this.caps[i] - a[i]) * this.mult[i] });
        if (a[i] > 0) out.push({ move: { kind: 'empty', i: i }, to: code - a[i] * this.mult[i] });
      }
    }
    for (i = 0; i < this.n; i++) {
      if (a[i] === 0) continue;
      for (j = 0; j < this.n; j++) {
        if (i === j || a[j] === this.caps[j]) continue;
        var amt = Math.min(a[i], this.caps[j] - a[j]);
        if (amt <= 0) continue;
        out.push({ move: { kind: 'pour', i: i, j: j, amt: amt }, to: code - amt * this.mult[i] + amt * this.mult[j] });
      }
    }
    return out;
  };

  /** Forward BFS from `start`. dist[code] = moves, or -1 if unreachable. */
  Space.prototype.reach = function (start) {
    var dist = new Array(this.total);
    for (var k = 0; k < this.total; k++) dist[k] = -1;
    dist[start] = 0;
    var q = [start], head = 0;
    while (head < q.length) {
      var c = q[head++];
      var e = this.edges(c);
      for (var i = 0; i < e.length; i++) {
        if (dist[e[i].to] !== -1) continue;
        dist[e[i].to] = dist[c] + 1;
        q.push(e[i].to);
      }
    }
    return { dist: dist, order: q };
  };

  /**
   * Reverse BFS: distance from every reachable state TO the nearest goal.
   * This is what powers both the optimal count and the hint, and it means the
   * hint is always a genuinely optimal move rather than a plausible one.
   */
  Space.prototype.toGoal = function (reachOrder, reachDist, isGoal) {
    var self = this;
    var rev = {};
    var d = {};
    var i, j, e;
    for (i = 0; i < reachOrder.length; i++) {
      var c = reachOrder[i];
      e = self.edges(c);
      for (j = 0; j < e.length; j++) {
        if (reachDist[e[j].to] === -1) continue;
        (rev[e[j].to] || (rev[e[j].to] = [])).push(c);
      }
    }
    var q = [], head = 0;
    for (i = 0; i < reachOrder.length; i++) {
      if (isGoal(self.decode(reachOrder[i]))) { d[reachOrder[i]] = 0; q.push(reachOrder[i]); }
    }
    while (head < q.length) {
      var cur = q[head++];
      var back = rev[cur] || [];
      for (j = 0; j < back.length; j++) {
        if (d[back[j]] !== undefined) continue;
        d[back[j]] = d[cur] + 1;
        q.push(back[j]);
      }
    }
    return d;
  };

