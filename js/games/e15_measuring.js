/* ==========================================================================
   PuzzleStudio — js/games/e15_measuring.js            ENGINE 15 · Measuring
   --------------------------------------------------------------------------
   Self-contained: logic + 3 skins + its own CSS. No DOM access until mount().

   THE PUZZLE
     The decanting problem, played straight. You have vessels of awkward,
     deliberately unhelpful capacities and you need an exact volume that is
     not written on any of them. Three operations and nothing else:

       FILL   a vessel to the brim from the source
       EMPTY  a vessel onto the ground
       POUR   one vessel into another until the source runs out or the
              destination is full — whichever happens first

     Everything is generated by BFS over the full state graph, so the target
     is provably reachable and the optimal move count is known exactly. You
     are scored against that number, not against a guess.

   THE ESCALATION
     Low tiers: two vessels and a tap you can use forever.
     Tier 3:    a third vessel, so the state space stops being a straight line.
     Tier 4+:   the tap is gone. What is already in the vessels is all there
                is, FILL and EMPTY do not exist, and you can only pour between
                them. That is a genuinely different and much nastier puzzle.

   THE ROOM (arena)
     The vessels are objects standing on the floor of a room, not widgets in a
     row. You pick one up, you carry it to the tap to fill it, to the drain to
     tip it out, or to another vessel to pour. Every move in the BFS is a walk
     across the room with something heavy in your hands, which is what the jug
     problem always was. The bench at the end of the room is the station: it
     keeps the count, the take-backs and, once it is measured, the choice.

   THE BRANCH
     Having measured it out, you either stay and draw off everything you can
     carry, or you take the one exact measure and move while you still can.
   ========================================================================== */
